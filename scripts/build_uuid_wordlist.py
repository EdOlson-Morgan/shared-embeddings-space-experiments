#!/usr/bin/env python3
"""Generate packages/uuid4-words/src/uuid_words/wordlist.py.

Pulls a frequency-ranked English word corpus (via the `wordfreq` package),
filters it down to plain, unambiguous, ASCII lowercase words, and then --
when `tiktoken` can reach its o200k_base vocab file over the network --
keeps only the words that encode as exactly one token. The result is
written as a static Python data file with no runtime dependency on either
package.

If tiktoken's vocab file is unreachable (e.g. blocked network egress),
this script falls back to the frequency-filtered candidates WITHOUT the
single-token check and marks the generated file UNVERIFIED. Re-run it from
an environment with network access to openaipublic.blob.core.windows.net
before relying on the module's token-count savings.

Usage:
    uv run --with wordfreq --with tiktoken scripts/build_uuid_wordlist.py
"""

from __future__ import annotations

import sys
from pathlib import Path

VOCAB_SIZE = 2048  # power of two; see docs/uuid-token-optimization-plan.md
MIN_LEN = 3
MAX_LEN = 9
CANDIDATE_POOL = 20_000  # top-N most frequent English words to consider

# Small, non-exhaustive blocklist of common profanity/slurs. Good enough to
# keep the provisional wordlist decent; swap in a maintained list (e.g.
# LDNOOBW) before treating this as production-ready.
_BLOCKED = frozenset(
    """
    anal anus arse ass bastard bitch bollocks boob boobs butt cock crap cunt
    damn dick dyke fag faggot fuck fucking gay homo jerk jizz nigger nigga
    piss porn pube pussy queer rape raped rapist retard shit slut spic
    tits titty twat wank whore wtf
    """.split()
)


def _load_candidates() -> list[str]:
    from wordfreq import top_n_list

    return top_n_list("en", CANDIDATE_POOL)


def _filter_candidates(words: list[str]) -> list[str]:
    seen: set[str] = set()
    kept: list[str] = []
    for word in words:
        if word in seen:
            continue
        seen.add(word)
        if not (MIN_LEN <= len(word) <= MAX_LEN):
            continue
        if not word.isascii() or not word.isalpha():
            continue
        if word in _BLOCKED:
            continue
        kept.append(word)
    return kept


def _single_token_filter(words: list[str]) -> tuple[list[str], bool]:
    """Return (filtered_words, verified). verified=False means tiktoken's
    vocab file could not be loaded, so no filtering was actually applied."""
    try:
        import tiktoken

        enc = tiktoken.get_encoding("o200k_base")
    except Exception as exc:  # network/proxy failure, missing package, etc.
        print(
            f"WARNING: could not load o200k_base ({exc!r}); "
            "shipping an UNVERIFIED wordlist. Re-run with network access "
            "to openaipublic.blob.core.windows.net before relying on "
            "token-count savings.",
            file=sys.stderr,
        )
        return words, False

    kept = [word for word in words if len(enc.encode(" " + word)) == 1]
    return kept, True


def _write_wordlist(words: list[str], verified: bool, out_path: Path) -> None:
    status = (
        "VERIFIED: every word is a single token under o200k_base"
        if verified
        else "**UNVERIFIED**: tiktoken/network was unavailable when this "
        "file was generated. Re-run scripts/build_uuid_wordlist.py from an "
        "environment with network access before relying on real token "
        "savings -- these words are only known to be common, plain English "
        "words, not confirmed single-token."
    )
    body = ",\n".join(f"    {word!r}" for word in words)
    out_path.write_text(
        f'"""Word list for UUIDv4 <-> words encoding.\n\n'
        f"Status: {status}\n"
        f"Size: {len(words)} words ({len(words).bit_length() - 1} bits/word)\n\n"
        f"Generated by scripts/build_uuid_wordlist.py -- do not hand-edit.\n"
        f'"""\n\n'
        f"WORDS: tuple[str, ...] = (\n{body},\n)\n"
    )
    print(f"wrote {len(words)} words to {out_path}\nstatus: {status}")


def main() -> None:
    candidates = _filter_candidates(_load_candidates())
    filtered_words, verified = _single_token_filter(candidates)
    pool = filtered_words if verified else candidates
    if len(pool) < VOCAB_SIZE:
        raise SystemExit(
            f"only {len(pool)} candidates survived filtering, need {VOCAB_SIZE}; "
            "widen CANDIDATE_POOL or relax the length/frequency filters."
        )
    # pool is frequency-ordered (most common first); keep the most common
    # VOCAB_SIZE, then sort alphabetically so the generated file diffs cleanly.
    chosen = sorted(pool[:VOCAB_SIZE])
    out_path = (
        Path(__file__).resolve().parent.parent
        / "packages/uuid4-words/src/uuid_words/wordlist.py"
    )
    _write_wordlist(chosen, verified, out_path)


if __name__ == "__main__":
    main()
